function toKey(month: number, day: number): string {
  return `${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
}

/**
 * Start times for a given month/day. February 29 falls back to February 28,
 * since the dataset is a 365-day recurring calendar.
 */
export function getStartTimesFor(month: number, day: number): SalahStartTimes | null {
  const tuple = START_TIMES[toKey(month, day)] ?? (month === 2 && day === 29 ? START_TIMES["02-28"] : undefined);
  if (!tuple) return null;
  const [fajr, sunrise, dhuhr, asr, maghrib, isha] = tuple;
  return { fajr, sunrise, dhuhr, asr, maghrib, isha };
}

/** Month and day at the masjid, independent of the visitor's own timezone. */
export function getMasjidMonthDay(now: Date = new Date()): { month: number; day: number } {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: MASJID_TIMEZONE,
    month: "numeric",
    day: "numeric",
  }).formatToParts(now);
  const get = (type: string) => Number(parts.find((p) => p.type === type)?.value);
  return { month: get("month"), day: get("day") };
}

/** Today's adhan times at the masjid. */
export function getTodayStartTimes(date: Date = new Date()): SalahStartTimes | null {
  const { month, day } = getMasjidMonthDay(date);
  return getStartTimesFor(month, day);
}
